import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import test from "node:test";

test("SMS OTP creates and links accounts safely under concurrent requests", { skip: !process.env.SECURITY_TEST_DATABASE_URL }, async (t) => {
  const url = new URL(process.env.SECURITY_TEST_DATABASE_URL!);
  assert.ok(["localhost", "127.0.0.1"].includes(url.hostname));
  assert.equal(url.pathname, "/ghafaseh_security_test");
  Object.assign(process.env, { DATABASE_URL: url.toString(), JWT_SECRET: "isolated-otp-test-secret-at-least-32-characters", SMS_PROVIDER: "kavenegar", SMS_DEV_MODE: "true", EMAIL_DEV_MODE: "true" });
  const { db, pool } = await import("@/db");
  const { User, Book, SmsVerificationCode, VerificationCode, PasswordResetToken } = await import("@/db/schema");
  const { eq, and } = await import("drizzle-orm");
  const { issueSmsOtp, verifySmsOtp } = await import("./sms-otp");
  const { issueVerificationCode, verifyVerificationCode } = await import("./verification-codes");
  const { resetPassword, authenticateUser } = await import("./service");
  const column = await pool.query("SELECT 1 FROM information_schema.columns WHERE table_name = 'User' AND column_name = 'phone'");
  if (!column.rowCount) await pool.query(readFileSync("drizzle/0077_sms_otp.sql", "utf8"));
  const recoveryColumn = await pool.query("SELECT 1 FROM information_schema.columns WHERE table_name = 'PasswordResetToken' AND column_name = 'verification_method'");
  if (!recoveryColumn.rowCount) await pool.query(readFileSync("drizzle/0078_sms_signup_recovery.sql", "utf8"));
  const phone = `+989${Math.floor(100_000_000 + Math.random() * 900_000_000)}`;
  const otherPhone = `+989${Math.floor(100_000_000 + Math.random() * 900_000_000)}`;
  const signupPhone = `+989${Math.floor(100_000_000 + Math.random() * 900_000_000)}`;
  const ownerId = randomUUID();
  const email = `otp-${ownerId}@example.test`;
  const resetCooldown = async (number: string) => pool.query('UPDATE "SmsVerificationCode" SET created_at = $2 WHERE phone = $1', [number, new Date(Date.now() - 61_000).toISOString()]);
  await db.insert(User).values({ id: ownerId, email, username: `otp-${ownerId.slice(0, 8)}`, password: "pre-hijacker", passwordHash: "pre-hijacker" });
  const [book] = await db.insert(Book).values({ userId: ownerId, title: "OTP fixture", author: "Writer", genre: "Novel", format: "PHYSICAL" }).returning({ id: Book.id });
  try {
    await t.test("parallel issuance and redemption produce one new account and one successful login", async () => {
      const issued = await Promise.allSettled(Array.from({ length: 8 }, () => issueSmsOtp(phone, "login")));
      const successes = issued.filter((result) => result.status === "fulfilled") as PromiseFulfilledResult<{ devCode?: string }>[];
      assert.equal(successes.length, 1);
      const code = successes[0].value.devCode!;
      assert.match(code, /^\d{6}$/);
      const verified = await Promise.allSettled(Array.from({ length: 8 }, () => verifySmsOtp(phone, code, "login")));
      assert.equal(verified.filter((result) => result.status === "fulfilled").length, 1);
      const users = await db.select().from(User).where(eq(User.phone, phone));
      assert.equal(users.length, 1);
      assert.equal(users[0].role, "USER");
      assert.equal(users[0].email, null);
      assert.equal(users[0].authProvider, "otp");
    });
    await t.test("parallel failed guesses respect the five-attempt ceiling", async () => {
      await resetCooldown(phone);
      const result = await issueSmsOtp(phone, "login");
      const wrong = result.devCode === "654321" ? "123456" : "654321";
      await Promise.allSettled(Array.from({ length: 12 }, () => verifySmsOtp(phone, wrong, "login")));
      const rows = await db.select().from(SmsVerificationCode).where(eq(SmsVerificationCode.phone, phone));
      assert.equal(rows.find((row) => row.attempts === 5)?.consumedAt instanceof Date, true);
      await assert.rejects(verifySmsOtp(phone, result.devCode!, "login"));
    });
    await t.test("linking requires the requesting account and current session, preserving its library", async () => {
      const { devCode } = await issueSmsOtp(otherPhone, "link", ownerId);
      await assert.rejects(verifySmsOtp(otherPhone, devCode!, "login"));
      await assert.rejects(verifySmsOtp(otherPhone, devCode!, "link", "another-user", 0), { code: "FORBIDDEN" });
      await assert.rejects(verifySmsOtp(otherPhone, devCode!, "link", ownerId, 1), { code: "UNAUTHENTICATED" });
      const user = await verifySmsOtp(otherPhone, devCode!, "link", ownerId, 0);
      assert.equal(user.id, ownerId);
      assert.equal(user.sessionVersion, 1);
      const [kept] = await db.select({ userId: Book.userId }).from(Book).where(eq(Book.id, book.id));
      assert.equal(kept.userId, ownerId);
      await resetCooldown(otherPhone);
      const login = await issueSmsOtp(otherPhone, "login");
      assert.equal((await verifySmsOtp(otherPhone, login.devCode!, "login")).id, ownerId);
      await resetCooldown(phone);
      const conflict = await issueSmsOtp(phone, "link", ownerId);
      await assert.rejects(verifySmsOtp(phone, conflict.devCode!, "link", ownerId, 1), { code: "PHONE_TAKEN" });
    });
    await t.test("provider failure leaves no redeemable SMS challenge", async () => {
      const failedPhone = "+989000000001";
      delete process.env.SMS_DEV_MODE;
      delete process.env.KAVENEGAR_API_KEY;
      delete process.env.KAVENEGAR_OTP_TEMPLATE;
      await assert.rejects(issueSmsOtp(failedPhone, "login"), { code: "SMS_NOT_CONFIGURED" });
      const rows = await db.select().from(SmsVerificationCode).where(eq(SmsVerificationCode.phone, failedPhone));
      assert.equal(rows.length, 0);
      process.env.SMS_DEV_MODE = "true";
    });
    await t.test("optional email login proves ownership and removes an unverified registration's password", async () => {
      const issued = await issueVerificationCode({ email, purpose: "login", requireExistingUser: true });
      const result = await verifyVerificationCode({ email, code: issued.devCode!, purpose: "login" });
      assert.equal(result.status, "verified");
      const [user] = await db.select().from(User).where(eq(User.id, ownerId));
      assert.equal(user.password, null);
      assert.equal(user.passwordHash, null);
      assert.ok(user.emailVerified);
      assert.equal(user.sessionVersion, 2);
      assert.equal((result as { sessionVersion?: number }).sessionVersion, 2);
      const [record] = await db.select().from(VerificationCode).where(and(eq(VerificationCode.email, email), eq(VerificationCode.purpose, "login")));
      assert.equal(record.deliveryAccepted, true);
    });
    await t.test("phone signup requires a password and phone proof without overwriting an existing account", async () => {
      const challenge = await issueSmsOtp(signupPhone, "signup");
      await assert.rejects(verifySmsOtp(signupPhone, challenge.devCode!, "login"), { code: "INVALID_CODE" });
      await assert.rejects(verifySmsOtp(signupPhone, challenge.devCode!, "signup"), { code: "INVALID_PASSWORD" });
      const wrong = challenge.devCode === "123456" ? "654321" : "123456";
      await assert.rejects(verifySmsOtp(signupPhone, wrong, "signup", undefined, undefined, undefined, "SignupPassword123"), { code: "INVALID_CODE" });
      assert.equal((await db.select().from(User).where(eq(User.phone, signupPhone))).length, 0);
      const user = await verifySmsOtp(signupPhone, challenge.devCode!, "signup", undefined, undefined, undefined, "SignupPassword123");
      assert.equal(user.name, "کاربر قفسه");
      assert.equal(user.email, null);
      const [stored] = await db.select().from(User).where(eq(User.id, user.id));
      assert.notEqual(stored.passwordHash, "SignupPassword123");
      assert.equal(stored.authProvider, "password");
      assert.equal((await authenticateUser({ identifier: signupPhone, password: "SignupPassword123" })).id, user.id);
      await resetCooldown(signupPhone);
      const repeated = await issueSmsOtp(signupPhone, "signup");
      const existing = await verifySmsOtp(signupPhone, repeated.devCode!, "signup", undefined, undefined, "نام جدید", "OtherPassword123");
      assert.equal(existing.id, user.id);
      assert.equal(existing.name, user.name);
      assert.equal((await authenticateUser({ identifier: signupPhone, password: "SignupPassword123" })).id, user.id);
      await assert.rejects(authenticateUser({ identifier: signupPhone, password: "OtherPassword123" }), { code: "INVALID_CREDENTIALS" });
    });
    await t.test("SMS recovery is one-use, keeps the library and does not verify the account email", async () => {
      const unknownPhone = "+989000000002";
      assert.deepEqual(await issueSmsOtp(unknownPhone, "recovery"), {});
      await assert.rejects(verifySmsOtp(unknownPhone, "123456", "recovery"), { code: "INVALID_CODE" });
      assert.equal((await db.select().from(User).where(eq(User.phone, unknownPhone))).length, 0);
      await db.update(User).set({ emailVerified: null }).where(eq(User.id, ownerId));
      await resetCooldown(otherPhone);
      const challenge = await issueSmsOtp(otherPhone, "recovery");
      await assert.rejects(verifySmsOtp(otherPhone, challenge.devCode!, "login"), { code: "INVALID_CODE" });
      const attempts = await Promise.allSettled(Array.from({ length: 8 }, () => verifySmsOtp(otherPhone, challenge.devCode!, "recovery")));
      const successful = attempts.filter((value) => value.status === "fulfilled") as PromiseFulfilledResult<Awaited<ReturnType<typeof verifySmsOtp>>>[];
      assert.equal(successful.length, 1);
      const recovered = successful[0].value;
      assert.equal(recovered.id, ownerId);
      assert.ok("resetToken" in recovered);
      assert.match(recovered.resetToken, /^[a-f0-9]{64}$/);
      const tokens = await db.select().from(PasswordResetToken).where(eq(PasswordResetToken.userId, ownerId));
      assert.equal(tokens.find((token) => !token.usedAt)?.verificationMethod, "sms");
      await resetPassword({ token: recovered.resetToken, password: "RecoveredPassword123" });
      await assert.rejects(resetPassword({ token: recovered.resetToken, password: "OtherPassword123" }), { code: "INVALID_RESET_TOKEN" });
      const [user] = await db.select().from(User).where(eq(User.id, ownerId));
      assert.equal(user.emailVerified, null);
      assert.equal(user.sessionVersion, 3);
      assert.equal((await authenticateUser({ identifier: `0${otherPhone.slice(3)}`, password: "RecoveredPassword123" })).id, ownerId);
      const [kept] = await db.select({ userId: Book.userId }).from(Book).where(eq(Book.id, book.id));
      assert.equal(kept.userId, ownerId);
    });
    await t.test("failed email delivery does not pretend success or leave a redeemable challenge", async () => {
      const env: NodeJS.ProcessEnv = { ...process.env, EMAIL_DEV_MODE: "false", EMAIL_MODE: "smtp" };
      for (const key of ["SMTP_HOST", "SMTP_USER", "SMTP_PASSWORD", "MAIL_FROM"]) delete env[key];
      const script = `import {issueVerificationCode} from './lib/auth/verification-codes'; import {pool} from './db'; (async()=>{try{await issueVerificationCode({email:${JSON.stringify(email)},purpose:'email_verification'});process.exitCode=1}catch(e){if(e.code!=='EMAIL_DELIVERY_FAILED')throw e}finally{await pool.end()}})()`;
      execFileSync(process.execPath, ["node_modules/tsx/dist/cli.mjs", "-e", script], { env, timeout: 15_000, stdio: ["ignore", "pipe", "pipe"] });
      const rows = await db.select().from(VerificationCode).where(and(eq(VerificationCode.email, email), eq(VerificationCode.purpose, "email_verification")));
      assert.equal(rows.length, 0);
    });
  } finally {
    await db.delete(SmsVerificationCode).where(eq(SmsVerificationCode.phone, phone));
    await db.delete(SmsVerificationCode).where(eq(SmsVerificationCode.phone, otherPhone));
    await db.delete(SmsVerificationCode).where(eq(SmsVerificationCode.phone, signupPhone));
    await db.delete(VerificationCode).where(eq(VerificationCode.email, email));
    await db.delete(User).where(eq(User.phone, phone));
    await db.delete(User).where(eq(User.phone, signupPhone));
    await db.delete(User).where(eq(User.id, ownerId));
    await pool.end();
  }
});
